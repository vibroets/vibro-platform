// scripts/generate-embedded-assets.mjs
//
// Regenerates embedded-asset TS modules from files in public/ so that the
// login slideshow, logo, manifest, icons, favicon, and service worker are
// bundled into the JS (served via /_next/static/...) or served via Next.js
// route handlers — NOT fetched from /public/ at runtime.
//
// This makes the app fully self-contained and immune to static-file serving
// issues (e.g. the 400 errors on www.vibroets.com for public/ files).
//
// Run automatically before `next build` and `next dev` via package.json scripts.
// Safe to run repeatedly — overwrites the generated files each time.

import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const pub = join(root, "public");

// ── helpers ──────────────────────────────────────────────────────────────

function readPublic(file) {
  const path = join(pub, file);
  if (!existsSync(path)) {
    throw new Error(`[generate-embedded-assets] Missing public file: ${file}`);
  }
  return readFileSync(path);
}

function dataUri(file, mimeType) {
  const buf = readPublic(file);
  return `data:${mimeType};base64,${buf.toString("base64")}`;
}

function writeTs(relPath, content) {
  const out = join(root, relPath);
  writeFileSync(out, content);
  console.log(`  ✓ ${relPath} (${(content.length / 1024).toFixed(1)} KB)`);
}

// ── 1. Slideshow HTML → app/login/slideshow-content.ts ────────────────────

function generateSlideshow() {
  const html = readPublic("video-slideshow.html").toString("utf8");
  const ts = `// AUTO-GENERATED by scripts/generate-embedded-assets.mjs from public/video-slideshow.html.
// Do not edit by hand — edit the HTML file and re-run the build script.
// Embedded (not fetched) so the login slideshow always renders, independent
// of static-file serving.
export const slideshowHtml = ${JSON.stringify(html)};
`;
  writeTs("app/login/slideshow-content.ts", ts);
}

// ── 2. Logo PNG → app/login/vibro-logo-data.ts ────────────────────────────

function generateLogo() {
  const uri = dataUri("vibro-logo.png", "image/png");
  const ts = `// AUTO-GENERATED by scripts/generate-embedded-assets.mjs from public/vibro-logo.png.
// Do not edit by hand.
export const vibroLogoDataUri = ${JSON.stringify(uri)};
`;
  writeTs("app/login/vibro-logo-data.ts", ts);
}

// ── 3. Favicon → app/embedded-favicon.ts ──────────────────────────────────

function generateFavicon() {
  const uri = dataUri("icons/192x192.png", "image/png");
  const ts = `// AUTO-GENERATED by scripts/generate-embedded-assets.mjs from public/icons/192x192.png.
// Do not edit by hand.
export const faviconDataUri = ${JSON.stringify(uri)};
`;
  writeTs("app/embedded-favicon.ts", ts);
}

// ── 4. Manifest JSON (with icons inlined) → app/embedded-manifest.ts ──────
// The manifest JSON is embedded as a string. A route handler at
// app/manifest.json/route.ts serves it with the correct content-type,
// overriding the broken public/manifest.json static file.

function generateManifest() {
  const manifest = JSON.parse(readPublic("manifest.json").toString("utf8"));

  // Inline every icon as a data URI so /icons/*.png are never fetched
  manifest.icons = (manifest.icons || []).map((icon) => {
    const src = icon.src.replace(/^\//, "");
    return { ...icon, src: dataUri(src, "image/png") };
  });

  const json = JSON.stringify(manifest);
  const ts = `// AUTO-GENERATED by scripts/generate-embedded-assets.mjs from public/manifest.json + public/icons/*.png.
// Do not edit by hand — edit manifest.json and re-run the build script.
// Served by app/manifest.json/route.ts (not from public/) to avoid 400 errors.
export const manifestJson = ${JSON.stringify(json)};
`;
  writeTs("app/embedded-manifest.ts", ts);
}

// ── main ─────────────────────────────────────────────────────────────────
// NOTE: The service worker (public/sw.js) is NOT embedded here because
// next-pwa generates it DURING `next build` (after this script runs).
// Instead, app/sw.js/route.ts reads public/sw.js from the filesystem at
// runtime, always serving the current version.

console.log("[generate-embedded-assets] Embedding public/ assets into TS modules...");
generateSlideshow();
generateLogo();
generateFavicon();
generateManifest();
console.log("[generate-embedded-assets] Done.");
